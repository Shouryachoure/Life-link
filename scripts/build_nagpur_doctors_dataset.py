def normalize_name(raw_name: str) -> str:
    name = re.sub(r'\s+', ' ', raw_name).strip()
    if not name.startswith("Dr.") and not name.startswith("Prof."):
        name = "Dr. " + name
    return name

def validate_mmc_format(reg_no: str) -> bool:
    if not reg_no:
        return False
    # Pattern: MMC/YYYY/MM/XXXXX or MMC-YYYY-MM-XXXXX or numeric MMC registration
    pattern = r'^(MMC[/-]?)?(\d{4}[/-]\d{2}[/-]\d{4,5}|\d{5,6})$'
    return bool(re.match(pattern, reg_no.strip(), re.IGNORECASE))

