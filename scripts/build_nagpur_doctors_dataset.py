    skipped = []

    for d in combined_doctors:
        norm_n = normalize_name(d['name']).lower()
        key = f"{norm_n}::{d['hospitalId']}"
        if key in seen:
            skipped.append({"name": d['name'], "hospitalId": d['hospitalId'], "reason": "DUPLICATE_NAME_AT_SAME_FACILITY"})
            continue
        seen[key] = True

        # Validation
        assert d['id'], "Doctor missing ID"
        assert d['name'], "Doctor missing name"
        assert d['specialization'], "Doctor missing specialization"
        assert d['hospitalId'], "Doctor missing hospitalId"
        assert d['sourceUrl'], "Doctor missing sourceUrl"

        deduped.append(d)

